// AND (&&): This operator returns true if both conditions are true, and false otherwise.
// OR (||): This operator returns true if at least one of the conditions is true, and false otherwise.
// NOT (!): This operator negates the value of a condition, returning true if the condition is false, and false if the condition is true.,

// && Gate
// || OR Gate
// ! Not Gate

